-- Algerian 58 Wilayas with delivery pricing
CREATE TABLE wilayas (
  id SERIAL PRIMARY KEY,
  code VARCHAR(2) NOT NULL UNIQUE,
  name_ar VARCHAR(100) NOT NULL,
  name_fr VARCHAR(100) NOT NULL,
  region VARCHAR(50) NOT NULL DEFAULT 'north',
  home_delivery_price DECIMAL(10,2) NOT NULL DEFAULT 600,
  desk_delivery_price DECIMAL(10,2) NOT NULL DEFAULT 400,
  home_delivery_days INT NOT NULL DEFAULT 3,
  desk_delivery_days INT NOT NULL DEFAULT 2,
  is_active BOOLEAN NOT NULL DEFAULT true,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE wilayas ENABLE ROW LEVEL SECURITY;
CREATE POLICY "wilayas_public_read" ON wilayas FOR SELECT USING (true);

